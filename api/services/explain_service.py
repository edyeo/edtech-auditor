import hashlib
import json
import logging
import os
from functools import lru_cache

from sqlalchemy.ext.asyncio import AsyncSession

from api.errors import ExplanationUnavailableError
from api.models.question import Question
from api.repositories.explanation_repository import ExplanationRepository
from api.repositories.question_repository import QuestionRepository
from api.services.llm.base import LLMProvider
from api.services.llm.fallback_provider import FallbackProvider
from api.services.question_service import QuestionService

# Maps LLM_PROVIDER env value -> (required key env var, import path).
# Add a new entry here when integrating another vendor (e.g. Anthropic).
_PROVIDERS: dict[str, tuple[str, str]] = {
    "openai": ("OPENAI_API_KEY", "api.services.llm.openai_provider:OpenAIProvider"),
    # TODO(oma-deferred): add "anthropic": ("ANTHROPIC_API_KEY", "api.services.llm.anthropic_provider:AnthropicProvider")
}


@lru_cache
def _resolve_provider() -> LLMProvider:
    provider_name = os.environ.get("LLM_PROVIDER", "openai")
    config = _PROVIDERS.get(provider_name)
    if config is None or not os.environ.get(config[0]):
        return FallbackProvider()

    module_path, class_name = config[1].split(":")
    module = __import__(module_path, fromlist=[class_name])
    provider_cls = getattr(module, class_name)
    return provider_cls()  # type: ignore[no-any-return]


logger = logging.getLogger(__name__)


def _content_hash(question: Question) -> str:
    """Identifies what an explanation was written for: stem, choices and the (corrected) answer key."""
    payload = {
        "stem": question.stem,
        "choices": question.choices,
        "answers": sorted({question.answer_index, *question.also_correct}),
    }
    return hashlib.sha256(json.dumps(payload, ensure_ascii=False, sort_keys=True).encode()).hexdigest()


class ExplainService:
    """Question-level explanations, generated by the LLM at most once per question and then reused.

    The explanation does not depend on the learner's choice, so one stored text serves everyone.
    """

    def __init__(self, repository: QuestionRepository | None = None) -> None:
        self._questions = QuestionService(repository)

    async def explain(self, session: AsyncSession | None, *, question_id: str) -> str:
        question = (await self._questions.resolve(session, [question_id]))[question_id]
        provider = _resolve_provider()
        answer_indexes = [question.answer_index, *question.also_correct]

        if session is None:  # no database: nothing to store, so every call goes to the provider
            return await self._generate(provider, question, answer_indexes)

        # `resolve` already opened this session's transaction; the advisory lock below lives in it
        # until the commit at the end.
        content_hash = _content_hash(question)
        store = ExplanationRepository(session)
        if (cached := await store.get(question_id, content_hash)) is not None:
            return cached

        # Single-flight: concurrent requests for the same question queue here, and every request
        # after the first finds the stored text on the re-check (READ COMMITTED sees its commit).
        await store.lock(question_id, content_hash)
        if (cached := await store.get(question_id, content_hash)) is not None:
            return cached

        explanation = await self._generate(provider, question, answer_indexes)
        if provider.persistable:
            await store.add(question_id, content_hash, explanation, provider.name)
        await session.commit()
        return explanation

    @staticmethod
    async def _generate(provider: LLMProvider, question: Question, answer_indexes: list[int]) -> str:
        try:
            return await provider.explain(
                stem=question.stem, choices=question.choices, answer_indexes=answer_indexes
            )
        except ExplanationUnavailableError:
            raise
        except Exception as exc:  # vendor SDK errors (network, rate limit, auth) all mean "no explanation"
            logger.exception("explanation provider %s failed for %s", provider.name, question.id)
            raise ExplanationUnavailableError() from exc
